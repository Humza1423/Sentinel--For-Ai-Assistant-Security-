"""Bounded memo attacks against the same assistant runtime used by chat."""

from __future__ import annotations

import hashlib
from collections.abc import Callable
from typing import Literal, Protocol
from uuid import UUID, uuid4

from langchain_core.language_models.fake_chat_models import FakeMessagesListChatModel
from langchain_core.messages import AIMessage, HumanMessage, SystemMessage
from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator

from .bank import BOB_ID, BOB_MARKER, SnapshotBankRepository
from .evidence import EvidenceError, EvidenceRecorder, canonical_json, read_events
from .live_model import MeteredOpenAIModel
from .observed_scoring import CrossCustomerVerdict, score_cross_customer_run
from .runtime import AssistantRun, run_assistant
